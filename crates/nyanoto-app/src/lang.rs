use crate::Words;

#[derive(Clone, Copy, PartialEq, Eq, Debug, Default)]
pub enum Lang {
    #[default]
    Ru,
    En,
}

impl Lang {
    pub fn code(self) -> &'static str {
        match self {
            Lang::Ru => "ru",
            Lang::En => "en",
        }
    }

    pub fn from_code(code: &str) -> Self {
        if code == "en" { Lang::En } else { Lang::Ru }
    }

    /// Номер в выпадающем списке языков в настройках.
    pub fn index(self) -> i32 {
        match self {
            Lang::Ru => 0,
            Lang::En => 1,
        }
    }

    pub fn from_index(index: i32) -> Self {
        if index == 1 { Lang::En } else { Lang::Ru }
    }

    pub fn lex(self) -> &'static Lex {
        match self {
            Lang::Ru => &RU,
            Lang::En => &EN,
        }
    }
}

